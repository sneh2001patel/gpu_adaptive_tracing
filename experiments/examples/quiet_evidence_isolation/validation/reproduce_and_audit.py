"""CPU regression proof and immutable re-audit of the original live campaign."""
import contextlib,hashlib,io,json,runpy,tarfile,types,unittest
from pathlib import Path
from unittest.mock import patch
from experiments.feasibility.challenge_freeze import validate_freeze
from experiments.feasibility.challenge_protocol_v2 import load_prepared
from experiments.feasibility import activity
from experiments.tests import test_owned_live_activity

ROOT=Path(__file__).resolve().parents[4]
OUT=Path(__file__).resolve().parent
BASE=ROOT/'experiments/hardware/l4_20261028'
def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def read(path):return json.loads(path.read_text())
snapshots=[ROOT/'experiments/examples/challenge_runner/snapshot_001',ROOT/'experiments/examples/event_challenges_v2/snapshot_001']
archives=[snapshots[0]/'source_step030.tar.gz',snapshots[1]/'source_step032.tar.gz']
expected_archives=['c4bc872cb5eb0fe583e29ab94bef6c7afd466f482a80dd77b1a93bb0b18fa747','a90db959b3abc2f2c472c0b450c68e8fcc89cb0ef7ecb06810ec892421f8aa51']
expected_descriptors=['07f3bc3270ff5a404569a318c8ca320f7ebad14b1f23b9250716a40a138615d9','60587c553e979b1103497f10685241dbfe282980565e19b723bfc59cf8972ec9']
entry_counts=[]
for snapshot,archive,expected,descriptor in zip(snapshots,archives,expected_archives,expected_descriptors):
    assert sha(archive)==expected and sha(snapshot/'FREEZE.json')==descriptor
    freeze=read(snapshot/'FREEZE.json')
    with tarfile.open(archive) as tar:
        for name,digest in freeze['files'].items():assert hashlib.sha256(tar.extractfile(name).read()).hexdigest()==digest
    entry_counts.append(len(freeze['files']))
with tarfile.open(archives[1]) as tar:
    frozen_source=tar.extractfile('experiments/feasibility/activity.py').read()
old=types.ModuleType('step032_frozen_activity')
exec(compile(frozen_source,'step032_frozen_activity.py','exec'),old.__dict__)
# The archived method has separate globals. Forward its HTTP dependency to
# the test-patched module so the reproduction cannot contact a live endpoint.
async def fixture_http(*args,**kwargs):return await activity.http_body(*args,**kwargs)
old.http_body=fixture_http
stream=io.StringIO()
with patch.object(test_owned_live_activity,'OwnedLiveActivity',old.OwnedLiveActivity):
    suite=unittest.TestSuite([test_owned_live_activity.ActivityTests('test_multiple_jobs_reuse_names_but_keep_only_their_own_hashes_and_rows')])
    result=unittest.TextTestRunner(stream=stream,verbosity=2).run(suite)
(OUT/'frozen_regression_reproduction.log').write_text(stream.getvalue())
assert len(result.failures)==1 and not result.errors and '8 != 4' in result.failures[0][1],stream.getvalue()
# Replay the old independent audit while intercepting its only report write:
# the newly generated bytes must equal the existing report, never replace it.
report=BASE/'CHALLENGES_V2_VALIDATION.json';existing=report.read_bytes();captured=io.StringIO();writes=[]
def compare_only(path,data,*args,**kwargs):
    assert path.resolve()==report and data.encode()==existing,'Unexpected mutation or changed historical audit'
    writes.append(str(path));return len(data)
with patch.object(Path,'write_text',compare_only),contextlib.redirect_stdout(captured):
    runpy.run_path(str(BASE/'challenges_v2_033_deployment/validate_backup.py'),run_name='__main__')
assert len(writes)==1 and report.read_bytes()==existing
(OUT/'live_campaign_reaudit.log').write_text(captured.getvalue())
failed=BASE/'challenges_001'
for name,digest in read(failed/'artifact_manifest.json')['files'].items():assert sha(failed/name)==digest
assert read(failed/'RESULT.json')['status']=='failed' and read(failed/'RESULT.json')['selection'] is None
for path,expected in [(BASE/'challenges_031_deployment/results_backup.tar.gz','8686b5b489dc6edb350a08a929a4845bacd2155f9bb0e29f2e204c7eaa14d40e'),
                      (BASE/'challenges_v2_033_deployment/results_backup.tar.gz','90fff5eb8864fddf66d23c345a1bec08841469f10a9ae8a291e8bbc7d751aa54')]:assert sha(path)==expected
with tarfile.open(BASE/'challenges_v2_033_deployment/results_backup.tar.gz') as tar:
    archived_manifest=tar.extractfile('experiments/hardware/l4_20261028/challenges_v2_001/artifact_manifest.json').read()
assert archived_manifest==(BASE/'challenges_v2_001/artifact_manifest.json').read_bytes()
try:validate_freeze(ROOT,ROOT/'experiments/examples/event_challenges_v2/prepared_001',snapshots[1]/'FREEZE.json',loader=load_prepared)
except ValueError as exc:
    assert str(exc).startswith('Source/input changed after freeze: ')
    working_rejection=str(exc)
else:raise AssertionError('Old freeze must reject revised working source')
summary=dict(audit_passed=True,GPU_used=False,SSH_used=False,
    frozen_regression_reproduced=True,frozen_regression_failure='second job saves eight rows instead of four',
    archived_entries_verified=entry_counts,original_failed_artifacts_verified=len(read(failed/'artifact_manifest.json')['files']),
    original_v1_still_failed=True,live_campaign_reaudit_passed=True,live_artifact_hashes_verified=6142,
    historical_validation_report_unchanged=True,original_archives_descriptors_and_backups_unchanged=True,
    working_source_rejected_by_old_freeze=working_rejection,new_engineering_snapshot_created=False,
    frozen_activity_sha256=hashlib.sha256(frozen_source).hexdigest(),working_activity_sha256=sha(ROOT/'experiments/feasibility/activity.py'),
    references_created=0,study_ready=False,protocol_frozen=False)
(OUT/'PRESERVATION.json').write_text(json.dumps(summary,indent=2)+'\n')
print(json.dumps(summary,indent=2))
